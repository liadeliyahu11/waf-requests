"""Stamp a `## Wire example` section into every technique page.

Examples are GENERATED by applying the real transform to a representative
request, so the before/after bytes on each docs page can never drift from the
implementation. Idempotent: existing sections are replaced, not duplicated.

Run: .venv/bin/python scripts/stamp_wire_examples.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from waf_requests import TRANSFORMS, Ctx  # noqa: E402
from waf_requests.fidelity import tier_of  # noqa: E402
from waf_requests.spec import ReqSpec, to_prepared  # noqa: E402

SQLI = "' OR '1'='1"
DOCS = Path(__file__).resolve().parents[1] / "docs" / "techniques"
DISPLAY_LIMIT = 256  # shrink pad geometry so printouts stay readable


def json_spec():
    return ReqSpec("POST", "http://shop.test/search",
                   {"Content-Type": "application/json"},
                   json.dumps({"q": SQLI}).encode())


def form_spec():
    return ReqSpec("POST", "http://shop.test/search",
                   {"Content-Type": "application/x-www-form-urlencoded"},
                   f"q={SQLI}".encode())


def multipart_spec():
    boundary = "XyZ123"
    body = (
        f"--{boundary}\r\n"
        'Content-Disposition: form-data; name="q"\r\n\r\n'
        f"{SQLI}\r\n"
        f"--{boundary}--\r\n"
    ).encode()
    return ReqSpec("POST", "http://shop.test/upload",
                   {"Content-Type": f"multipart/form-data; boundary={boundary}"}, body)


def two_part_multipart():
    b = "B2"
    body = (
        f"--{b}\r\n"
        'Content-Disposition: form-data; name="first"\r\n\r\none\r\n'
        f"--{b}\r\n"
        'Content-Disposition: form-data; name="second"\r\n\r\ntwo\r\n'
        f"--{b}--\r\n"
    ).encode()
    return ReqSpec("POST", "http://shop.test/upload",
                   {"Content-Type": f"multipart/form-data; boundary={b}"}, body)


def get_spec():
    from urllib.parse import quote

    return ReqSpec("GET", "http://shop.test/search?q=" + quote(SQLI, safe=""),
                   {"User-Agent": "exploit/1.0"}, None)


def two_pair_query():
    return ReqSpec("GET", "http://shop.test/s?a=1&q=" + SQLI.replace(" ", "+"),
                   {}, None)


def dotted_path():
    return ReqSpec("GET", "http://shop.test/a/b.c", {}, None)


def slashy_path():
    return ReqSpec("GET", "http://shop.test/a/b", {}, None)


def traversal_spec():
    return ReqSpec("GET", "http://shop.test/files/../secret.txt",
                   {"User-Agent": "exploit/1.0"}, None)


def plain_file_spec():
    return ReqSpec("GET", "http://shop.test/files/report.txt", {}, None)


def ua_spec():
    return ReqSpec("GET", "http://shop.test/search",
                   {"User-Agent": "<script>alert(1)</script>"}, None)


