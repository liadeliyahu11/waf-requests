# Transforms whose output is too tall for the default body preview window.
BODY_PREVIEW_OVERRIDES = {
    "json_deep_nest_wrap": 220,
}


def _collapse(text: str) -> str:
    """Shrink filler runs (spaces, AAAA..., [[[[...) to counted markers.

    Long irrelevant runs become `<Nx 'c'>`; everything else - especially
    payload characters - stays byte-for-byte.
    """
    import re as _re

    def sub(match):
        run = match.group(0)
        return f"<{len(run)}x {run[0]!r}>"

    return _re.sub(r"(.)\1{23,}", sub, text)


def render(prep, max_body=170) -> str:
    """Origin-form wire; filler collapsed; head+tail kept on cut."""
    from urllib.parse import urlsplit

    parts = urlsplit(prep.url)
    target = parts.path or "/"
    if parts.query:
        target += "?" + parts.query
    lines = [f"{prep.method} {target} HTTP/1.1", f"Host: {parts.netloc}"]
    for key, value in prep.headers.items():
        shown_value = _collapse(str(value))
        if len(shown_value) > 110:
            cut = len(shown_value) - 100
            shown_value = shown_value[:60] + f" ...[{cut} chars hidden]... " \
                + shown_value[-40:]
        lines.append(f"{key}: {shown_value}")
    body = prep.body or b""
    if isinstance(body, str):
        body = body.encode()
    if body:
        try:
            text = body.decode("utf-8")
            nonprintable = sum(
                not c.isprintable() and c not in "\r\n\t" for c in text)
            if nonprintable > len(text) * 0.3:
                raise UnicodeDecodeError("utf-8", body, 0, 1, "binary-ish")
        except UnicodeDecodeError:
            encoding = next((str(v) for k, v in prep.headers.items()
                             if k.lower() == "content-encoding"), "")
            lines.append("")
            lines.append(f"<{len(body)} bytes of {encoding or 'binary'} data>")
            return "\n".join(lines)
        text = _collapse(text.replace("\r\n", "\n"))
        lines.append("")
        if len(text) > max_body:
            half = max_body // 2
            lines.append(text[:half].rstrip("\n"))
            lines.append("...[filler-only bytes hidden]...")
            lines.append(text[-half:].lstrip("\n"))
        else:
            lines.append(text)
    return "\n".join(lines)

IMPACT_TEXT = {
    "transparent": (
        "**Impact: guaranteed.** Once this transform delivers, a conforming"
        "\norigin has interpreted the ORIGINAL payload byte-for-byte - the"
        "\nexploit lands regardless of application stack."),
    "additive": (
        "**Impact: guaranteed for the original fields.** Decoys are extra"
        "\ndistinct-name parameters/parts no exploit reads."),
    "differential": (
        "**Impact: conditional.** The wire payload DIFFERS from the original;"
        "\nthe origin interprets it correctly only if its parser behaves as"
        "\ndocumented here. Delivery alone is not exploitation - prove it with"
        "\n`python -m waf_requests verify <url>`."),
}


def upsert_section(page: Path) -> str:
    text = page.read_text()
    anchor = "## Prerequisites and limits"
    assert anchor in text, page.name
    block = section_for(page.stem)
    start = text.find("## Wire example")
    if start >= 0:
        text = text[:start] + block + "\n" + text[text.find(anchor):]
        action = "replaced"
    else:
        text = text.replace(anchor, block + "\n" + anchor, 1)
        action = "inserted"

    import re as _re

    tier = tier_of(page.stem)
    impact = f"> **Impact:** {IMPACT_TEXT[tier]}"
    if "> **Impact:**" in text:
        text = _re.sub(r"> \*\*Impact:\*\*[^\n]*(\n[^\n>#][^\n]*)*", impact, text,
                       count=1)
    else:
        text = _re.sub(r"^(Category: .*)$", r"\1\n\n" + impact, text,
                       count=1, flags=_re.M)
    page.write_text(text)
    return action


def section_for(tid: str) -> str:
    factory, ctx = FIXTURES[tid]
    spec = factory()
    out = TRANSFORMS[tid].apply(spec, ctx)
    assert out is not None, tid
    tier = tier_of(tid)
    note = ""
    if ctx.profile_limit == DISPLAY_LIMIT and "pad" in tid or tid == "header_pad_early":
        note = (f"\nThe inspection window is shrunk to {DISPLAY_LIMIT} bytes here so"
                "\nthe pad geometry fits on screen.")
    max_body = BODY_PREVIEW_OVERRIDES.get(tid, 170)
    return (
        f"## Wire example\n\n"
        f"Generated by applying this transform to a representative request "
        f"(fidelity tier: **{tier}**).{note}\n\n"
        f"Original:\n\n```http\n{render(to_prepared(spec), max_body)}\n```\n\n"
        f"After `{tid}`:\n\n```http\n{render(to_prepared(out), max_body)}\n```\n"
    )




def main() -> int:
    counts = {"inserted": 0, "replaced": 0}
    for tid in sorted(TRANSFORMS):
        action = upsert_section(DOCS / f"{tid}.md")
        counts[action] += 1
    print(f"inserted={counts['inserted']} replaced={counts['replaced']} "
          f"total={len(TRANSFORMS)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
